  var storage = global.App && global.App.Storage;
  var current = 'zh-CN';
  // 语言异步读取：app.js 启动时会等待 ready，避免首屏闪烁成默认语言
  var ready = (storage ? storage.init().then(function () { return storage.kvGet('locale'); }) : Promise.resolve(null))
    .then(function (saved) {
      if (saved && dictionaries[saved]) current = saved;
      return current;
    }).catch(function () { return current; });

  var listeners = [];

  function t(key, params) {
    var table = dictionaries[current] || dictionaries.en;
    var value = table[key];
    if (value === undefined) value = dictionaries.en[key];
    if (value === undefined) value = key;
    if (params) {
      value = String(value).replace(/\{(\w+)\}/g, function (match, name) {
        return params[name] === undefined || params[name] === null ? match : String(params[name]);
      });
    }
    return value;
  }

  function apply(root) {
    var scope = root || document;
    if (!scope.querySelectorAll) return;
    var nodes = scope.querySelectorAll('[data-i18n]');
    Array.prototype.forEach.call(nodes, function (node) {
      node.textContent = t(node.getAttribute('data-i18n'));
    });
    nodes = scope.querySelectorAll('[data-i18n-placeholder]');
    Array.prototype.forEach.call(nodes, function (node) {
      node.setAttribute('placeholder', t(node.getAttribute('data-i18n-placeholder')));
    });
    nodes = scope.querySelectorAll('[data-i18n-title]');
    Array.prototype.forEach.call(nodes, function (node) {
      node.setAttribute('title', t(node.getAttribute('data-i18n-title')));
    });
  }

  function setLocale(locale) {
    if (!dictionaries[locale]) return false;
    current = locale;
    if (storage) storage.kvPut('locale', locale).catch(function () { /* 忽略 */ });
    listeners.forEach(function (fn) { fn(locale); });
    if (typeof document !== 'undefined') apply(document);
    return true;
  }

  global.App = global.App || {};
  global.App.I18n = {
    t: t,
    ready: ready,
    apply: apply,
    setLocale: setLocale,
    locale: function () { return current; },
    locales: function () {
      return [
        { code: 'zh-CN', label: '简体中文' },
        { code: 'en', label: 'English' },
        { code: 'ja', label: '日本語' }
      ];
    },
    onChange: function (fn) { listeners.push(fn); }
  };
