/**
 * 地块的购买规则（不生成，手写）。
 *
 * 以前「第几块地」由等级决定（`PLOT_UNLOCK_LV`）。现在改成**存在地块上**：
 * 每块地自带 `usable` 字段，落库、跟着存档走 —— 这样才好在联机时只把
 * 对方用得上的地同步出去，也让「买地」成为一个真正的金币去处。
 *
 * 开局送 6 块，之后每买一块都更贵：
 *
 *   第 7 块   (6-6)*1000 + 500 =   500
 *   第 8 块   (7-6)*1000 + 500 =  1500
 *   …
 *   第 40 块 (39-6)*1000 + 500 = 33500
 *
 * 全买下来大约 58 万金币，是后期主要的经济出口之一。
 */

/** 开局就有的地块数 */
export const FREE_PLOTS = 6;

/**
 * 下一块地的价格。
 * @param {number} owned 当前已拥有的地块数
 * @returns {number} 金币
 */
export const plotPrice = (owned) => Math.max(0, owned - FREE_PLOTS) * 1000 + 500;
